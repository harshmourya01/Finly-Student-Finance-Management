CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deduplication_key VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    message VARCHAR(1000) NOT NULL,
    related_entity_id BIGINT,
    title VARCHAR(120) NOT NULL,
    type VARCHAR(40) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_notification_user_dedupe UNIQUE (user_id, deduplication_key),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);
CREATE INDEX idx_notification_user_created ON notifications (user_id, created_at);
CREATE INDEX idx_notification_user_read ON notifications (user_id, is_read);

CREATE TABLE financial_idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    operation_type VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(120) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_body VARCHAR(8192) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_fin_idem_user_operation_key UNIQUE (user_id, operation_type, idempotency_key),
    CONSTRAINT fk_fin_idem_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);
