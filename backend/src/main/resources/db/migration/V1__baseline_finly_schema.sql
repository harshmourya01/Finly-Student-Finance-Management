-- Initial schema for new installations. Existing installations are baselined at version 1.
-- All statements are additive; no existing application records are removed.
CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    email VARCHAR(150) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_user_email UNIQUE (email)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    name VARCHAR(80) NOT NULL,
    type VARCHAR(16) NOT NULL,
    CONSTRAINT uk_category_name_type UNIQUE (name, type)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    description VARCHAR(255) NOT NULL,
    notes VARCHAR(1000),
    payment_method VARCHAR(20) NOT NULL,
    transaction_date DATE NOT NULL,
    type VARCHAR(16) NOT NULL,
    category_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE TABLE budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    budget_month DATE NOT NULL,
    category_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_budget_user_category_month UNIQUE (user_id, category_id, budget_month),
    CONSTRAINT fk_budgets_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_budgets_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE TABLE savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    current_amount NUMERIC(19, 2) NOT NULL,
    name VARCHAR(120) NOT NULL,
    target_amount NUMERIC(19, 2) NOT NULL,
    target_date DATE NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_savings_goals_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    category VARCHAR(80) NOT NULL,
    frequency VARCHAR(16) NOT NULL,
    name VARCHAR(120) NOT NULL,
    next_renewal_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES app_users (id)
);
